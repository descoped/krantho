#!/usr/bin/env node
/**
 * Generate the Schema.org vocabulary table @krantho/seo validates against.
 *
 * Usage (from packages/seo):
 *   node scripts/generate-vocabulary.mjs --release 30.1
 *   node scripts/generate-vocabulary.mjs --release 30.1 --source ./schemaorg-all-https.jsonld
 *
 * Reads Schema.org's `schemaorg-all-https.jsonld` for the release (current and
 * retired terms), writes `src/vocabulary/schemaorg.generated.ts`, and prints
 * what changed against the table it replaces: new, removed, superseded,
 * retired and pending terms. Moving krantho to a newer Schema.org release is
 * this one command, followed by a review of the printed changes.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const OUTPUT = join(dirname(fileURLToPath(import.meta.url)), '../src/vocabulary/schemaorg.generated.ts')
const BEGIN = '// BEGIN VOCABULARY'
const END = '// END VOCABULARY'

function parseArgs(argv) {
  const args = {}
  for (let i = 0; i < argv.length; i += 2) {
    const key = argv[i]
    const value = argv[i + 1]
    if (!key?.startsWith('--') || value === undefined) usage()
    args[key.slice(2)] = value
  }
  if (!args.release || !/^\d+\.\d+$/.test(args.release)) usage()
  return args
}

function usage() {
  console.error('Usage: generate-vocabulary.mjs --release <major.minor> [--source <file>]')
  process.exit(1)
}

async function loadSource(args) {
  if (args.source) return JSON.parse(readFileSync(args.source, 'utf8'))
  const url = `https://schema.org/version/${args.release}/schemaorg-all-https.jsonld`
  const response = await fetch(url)
  if (!response.ok) throw new Error(`GET ${url} → ${response.status}`)
  return response.json()
}

const list = (value) => (value === undefined ? [] : Array.isArray(value) ? value : [value])
const ids = (value) => list(value).map((ref) => ref['@id'])
const term = (id) => (typeof id === 'string' && id.startsWith('schema:') ? id.slice(7) : null)
const terms = (value) => ids(value).map(term).filter((name) => name !== null).sort()

function lifecycleOf(node) {
  const parts = ids(node['schema:isPartOf'])
  if (parts.includes('https://attic.schema.org')) return { status: 'retired' }
  const by = terms(node['schema:supersededBy'])
  if (by.length > 0) return { status: 'superseded', by: by[0] }
  if (parts.includes('https://pending.schema.org')) return { status: 'pending' }
  return undefined
}

function withLifecycle(entry, node) {
  const lifecycle = lifecycleOf(node)
  return lifecycle ? { ...entry, lifecycle } : entry
}

/** Classes, properties and enumeration members of the release, keyed by term name */
function buildVocabulary(source) {
  const types = {}
  const properties = {}
  const members = {}
  for (const node of source['@graph']) {
    const name = term(node['@id'])
    if (name === null) continue
    const nodeTypes = list(node['@type'])
    if (nodeTypes.includes('rdfs:Class')) {
      const entry = { parents: terms(node['rdfs:subClassOf']) }
      if (nodeTypes.includes('schema:DataType')) entry.datatype = true
      types[name] = withLifecycle(entry, node)
    }
    if (nodeTypes.includes('rdf:Property')) {
      const entry = {
        domain: terms(node['schema:domainIncludes']),
        range: terms(node['schema:rangeIncludes']),
      }
      properties[name] = withLifecycle(entry, node)
    }
    const enumerations = nodeTypes.map(term).filter((type) => type !== null && type !== 'DataType')
    if (enumerations.length > 0) {
      members[name] = withLifecycle({ types: enumerations.sort() }, node)
    }
  }
  return { types: sorted(types), properties: sorted(properties), members: sorted(members) }
}

function sorted(record) {
  return Object.fromEntries(Object.entries(record).sort(([a], [b]) => a.localeCompare(b)))
}

function section(name, record) {
  const lines = Object.entries(record).map(
    ([key, value]) => `    ${JSON.stringify(key)}: ${JSON.stringify(value)},`,
  )
  return [`  ${JSON.stringify(name)}: {`, ...lines, '  },']
}

function render(release, vocabulary) {
  return [
    `// Generated by scripts/generate-vocabulary.mjs from Schema.org V${release} — do not edit.`,
    '// Regenerate: node scripts/generate-vocabulary.mjs --release <major.minor>',
    "import type { VocabularyData } from './types.js'",
    '',
    `export const SCHEMAORG_RELEASE = '${release}'`,
    '',
    'export const VOCABULARY: VocabularyData = {',
    BEGIN,
    ...section('types', vocabulary.types),
    ...section('properties', vocabulary.properties),
    ...section('members', vocabulary.members),
    END,
    '}',
    '',
  ].join('\n')
}

function readPrevious() {
  if (!existsSync(OUTPUT)) return null
  const text = readFileSync(OUTPUT, 'utf8')
  const start = text.indexOf(BEGIN)
  const end = text.indexOf(END)
  if (start < 0 || end < 0) return null
  const body = text.slice(start + BEGIN.length, end).trim().replace(/,$/, '')
  const release = /SCHEMAORG_RELEASE = '([^']+)'/.exec(text)?.[1] ?? '?'
  return { release, vocabulary: JSON.parse(`{${body.replace(/,(\s*})/g, '$1')}}`) }
}

function status(entry) {
  return entry?.lifecycle?.status ?? 'current'
}

/** Terms of every kind, so a class that became a property (or the reverse) still diffs */
function allTerms(vocabulary) {
  return { ...vocabulary.members, ...vocabulary.properties, ...vocabulary.types }
}

function report(previous, next, release) {
  if (!previous) {
    const counts = Object.entries(next).map(([kind, record]) => `${Object.keys(record).length} ${kind}`)
    console.log(`Schema.org V${release}: ${counts.join(', ')} (no previous table)`)
    return
  }
  const before = allTerms(previous.vocabulary)
  const after = allTerms(next)
  const changes = { new: [], removed: [], superseded: [], retired: [], pending: [] }
  for (const name of Object.keys(after)) {
    if (!(name in before)) changes.new.push(name)
    const was = status(before[name])
    const now = status(after[name])
    if (now !== was && now in changes) {
      const by = now === 'superseded' ? ` → ${after[name].lifecycle.by}` : ''
      changes[now].push(`${name}${by}`)
    }
  }
  for (const name of Object.keys(before)) if (!(name in after)) changes.removed.push(name)
  console.log(`Schema.org V${previous.release} → V${release}`)
  for (const [kind, names] of Object.entries(changes)) {
    console.log(`  ${kind}: ${names.length === 0 ? 'none' : names.join(', ')}`)
  }
}

const args = parseArgs(process.argv.slice(2))
const vocabulary = buildVocabulary(await loadSource(args))
const previous = readPrevious()
writeFileSync(OUTPUT, render(args.release, vocabulary))
report(previous, vocabulary, args.release)
console.log(`Wrote ${OUTPUT}`)
