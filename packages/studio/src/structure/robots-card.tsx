import { RotateCcw, Save } from 'lucide-react'
import { type ReactElement, useId, useState } from 'react'
import { ActionButton } from '../editor/action-button.js'
import {
  hasRobotsOverride,
  resetRobotsOverride,
  type SeoConfigData,
  saveRobotsOverride,
} from '../lib/api.js'
import { errorMessage } from '../lib/fetch.js'
import type { Served } from '../lib/served.js'
import { Chip } from '../ui/chip.js'
import { useToast } from '../ui/toast.js'
import { robotsServedText, servedFrom } from './crawlers-model.js'
import { StructureCard } from './structure-card.js'

export interface RobotsCardProps {
  /** What the site serves at /robots.txt, and what krantho's API answers */
  robots: { served: Served; krantho: string }
  /** The site's SEO settings, where an override is kept */
  site: SeoConfigData | null
  admin: boolean
  /** An override was saved or removed: read again */
  onSaved: () => void
}

type Busy = 'save' | 'reset' | null

function blocker(
  admin: boolean,
  busy: Busy,
  dirty: boolean,
  action: 'save' | 'reset',
): string | null {
  if (!admin) return 'robots.txt is changed by an admin.'
  if (busy) return 'Saving…'
  if (action === 'save' && !dirty) return 'Change the text first.'
  return null
}

/** Save the draft as the override, or remove the override; says what happened */
function useRobotsActions(onSaved: () => void): {
  busy: Busy
  save: (text: string) => void
  reset: () => void
} {
  const toast = useToast()
  const [busy, setBusy] = useState<Busy>(null)
  async function run(kind: 'save' | 'reset', action: () => Promise<string>): Promise<void> {
    setBusy(kind)
    try {
      toast({ text: await action() })
      onSaved()
    } catch (err: unknown) {
      toast({ text: errorMessage(err, 'robots.txt could not be saved'), tone: 'error' })
    } finally {
      setBusy(null)
    }
  }
  return {
    busy,
    save: (text) =>
      void run('save', async () => {
        await saveRobotsOverride(text)
        return 'Override saved. /api/seo/robots.txt now serves it.'
      }),
    reset: () =>
      void run('reset', async () =>
        (await resetRobotsOverride())
          ? 'Override removed. krantho generates robots.txt again.'
          : 'There was no override: krantho already generates robots.txt.',
      ),
  }
}

/** The text being edited: what krantho serves, until it is changed; a new answer starts it again */
function useDraft(served: string): [string, (draft: string) => void] {
  const [draft, setDraft] = useState(served)
  const [base, setBase] = useState(served)
  if (base !== served) {
    setBase(served)
    setDraft(served)
  }
  return [draft, setDraft]
}

/** Save keeps the draft as the override; Reset returns to the generated text */
function RobotsActions(props: {
  draft: string
  served: string
  admin: boolean
  onSaved: () => void
}): ReactElement {
  const { busy, save, reset } = useRobotsActions(props.onSaved)
  const dirty = props.draft !== props.served
  return (
    <div className="structure-actions">
      <ActionButton
        variant="primary"
        icon={Save}
        reason={blocker(props.admin, busy, dirty, 'save')}
        onClick={() => save(props.draft)}
      >
        {busy === 'save' ? 'Saving…' : 'Save'}
      </ActionButton>
      <ActionButton
        icon={RotateCcw}
        reason={blocker(props.admin, busy, dirty, 'reset')}
        onClick={reset}
      >
        {busy === 'reset' ? 'Resetting…' : 'Reset'}
      </ActionButton>
    </div>
  )
}

/**
 * robots.txt: what krantho serves, generated or the saved override, edited
 * in place; Save keeps the text as the override, Reset returns to the
 * generated one. Whether the site's own /robots.txt serves it is said.
 */
export function RobotsCard({ robots, site, admin, onSaved }: RobotsCardProps): ReactElement {
  const [draft, setDraft] = useDraft(robots.krantho)
  const fieldId = useId()
  const override = hasRobotsOverride(site)
  const origin = override
    ? 'The override saved in Studio'
    : 'Generated by krantho: every crawler allowed, the sitemap named'
  return (
    <StructureCard
      title="robots.txt"
      lead={`${origin}. ${robotsServedText(servedFrom(robots.served, robots.krantho))}`}
    >
      <div className="structure-row">
        <label htmlFor={fieldId} className="structure-label">
          robots.txt
        </label>
        <Chip tone={override ? 'accent' : 'neutral'}>{override ? 'Override' : 'Generated'}</Chip>
      </div>
      <textarea
        id={fieldId}
        className="structure-textarea"
        rows={8}
        spellCheck={false}
        value={draft}
        readOnly={!admin}
        onChange={(event) => setDraft(event.target.value)}
      />
      <RobotsActions draft={draft} served={robots.krantho} admin={admin} onSaved={onSaved} />
    </StructureCard>
  )
}
