import { DEFAULTS } from './defaults.js'
import type { LeafSpec } from './leaves.js'
import { envNameFor, LEAVES } from './leaves.js'
import { getPath } from './object-path.js'

/** Leaves whose default is computed from another leaf rather than written down */
const DERIVED_DEFAULTS: Record<string, string> = {
  'site.supportedLocales': 'the primary language alone',
  'site.defaultLocale': 'the primary language',
  'paths.seoGeneratedDir': '`<paths.contentDir>/seo/generated`',
  'persistence.sqlite.path': '`<paths.dataDir>/content.db`',
  'persistence.filesystem.contentPath': '`<paths.contentDir>`',
  'media.s3.publicUrl':
    '`https://<media.s3.bucket>.s3.<media.s3.region>.amazonaws.com` when media.s3.endpoint is unset',
  'media.gcs.publicUrl': '`https://storage.googleapis.com/<media.gcs.bucket>`',
}

const SECTION_TITLES: Record<string, string> = {
  site: 'Site identity',
  paths: 'Paths',
  persistence: 'Persistence',
  content: 'Content engine',
  cache: 'Page cache',
  auth: 'Authentication',
  media: 'Media and images',
  llm: 'Language model',
  assistant: 'Studio assistant',
  seo: 'SEO',
  webhooks: 'Webhooks',
  tools: 'Build-time tools',
}

const KIND_LABELS: Record<LeafSpec['kind'], string> = {
  string: 'string',
  int: 'integer',
  boolean: 'boolean',
  list: 'comma-separated list',
  structured: 'structured',
}

function renderValue(value: unknown): string {
  if (Array.isArray(value)) {
    if (value.length === 0) return '`[]`'
    return value.map((entry) => `\`${String(entry)}\``).join(', ')
  }
  if (value !== null && typeof value === 'object') return `\`${JSON.stringify(value)}\``
  return `\`${String(value)}\``
}

function renderDefault(leaf: LeafSpec): string {
  const derived = DERIVED_DEFAULTS[leaf.path]
  if (derived) return derived
  const value = getPath(DEFAULTS, leaf.path)
  if (value === undefined) return 'unset'
  return renderValue(value)
}

function renderRow(leaf: LeafSpec): string {
  const env = envNameFor(leaf)
  const variable = env === null ? 'code only' : `\`${env}\``
  const secret = leaf.secret ? ' **Secret.**' : ''
  const cells = [
    variable,
    `\`${leaf.path}\``,
    KIND_LABELS[leaf.kind],
    renderDefault(leaf),
    `${leaf.description}${secret}`,
  ]
  return `| ${cells.join(' | ')} |`
}

const PREAMBLE = `# Configuration reference

Every knob krantho reads, where it lives in \`krantho.config.ts\`, and the
environment variable that overrides it.

Values resolve in one pass at startup: **defaults, then code, then the
environment**. The environment wins. Every problem found — a bad value, a
missing required field, a rule spanning two leaves — is reported together in a
single startup error naming each variable and path.

Notes that apply to the whole table:

- A variable set to an empty string counts as unset.
- A **secret** leaf also accepts a \`_FILE\` suffix — \`KRANTHO_LLM_ANTHROPIC_API_KEY_FILE\`
  names a file whose trimmed contents become the value. The variable itself
  wins when both are set. Secrets never reach a browser and are replaced by
  \`[redacted]\` in any dump of the tree.
- A **comma-separated list** splits on commas and trims each entry.
- A **boolean** accepts \`true\`/\`false\`, \`1\`/\`0\`, \`yes\`/\`no\` and \`on\`/\`off\`.
- A **structured** leaf holds nested data and is set in code only.
- Relative filesystem paths resolve against the working directory.

<!-- Generated by envReference() in @krantho/config. Do not edit by hand. -->
`

/**
 * Render the whole configuration reference as markdown.
 *
 * This is the source of `docs/configuration.md`; regenerate it whenever a leaf
 * is added, renamed or given a different default.
 */
export function envReference(): string {
  const sections = new Map<string, LeafSpec[]>()
  for (const leaf of LEAVES) {
    const section = leaf.path.split('.')[0] ?? leaf.path
    const bucket = sections.get(section)
    if (bucket) bucket.push(leaf)
    else sections.set(section, [leaf])
  }

  const blocks: string[] = [PREAMBLE]
  for (const [section, leaves] of sections) {
    blocks.push(`## ${SECTION_TITLES[section] ?? section}\n`)
    blocks.push('| Variable | Path | Type | Default | Description |')
    blocks.push('| --- | --- | --- | --- | --- |')
    blocks.push(leaves.map(renderRow).join('\n'))
    blocks.push('')
  }

  return `${blocks.join('\n')}`
}
