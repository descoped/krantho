import { resolveJsonLd } from '@krantho/ui-react/server'
import type { Summary } from '../../lib/content'
import '../styles/how-made.css'

// "How this page is made": an unobtrusive disclosure at the end of every page.
// It shows the page template, the krantho documents it renders with their
// fields, and the JSON-LD krantho generated for it — the site demonstrating
// krantho instead of claiming anything about it.

interface Source {
  collection: string
  slug: string
  doc?: Summary | undefined
}

function fieldsOf(doc: Summary | undefined): [string, string][] {
  if (!doc) return []
  return Object.entries(doc.fields)
    .filter(([, value]) => value !== undefined && value !== null && value !== '')
    .map(([name, value]) => [name, Array.isArray(value) ? value.join(', ') : String(value)])
}

export async function HowMade({
  template,
  sources,
  jsonLd,
}: {
  /** The page template's file, relative to krantho-site/ */
  template: string
  /** The documents this page renders; the first one's JSON-LD is shown */
  sources: Source[]
  /** Show the JSON-LD of the first source (default true) */
  jsonLd?: boolean
}): Promise<React.ReactElement> {
  const [primary] = sources
  let graph = ''
  if (primary && jsonLd !== false) {
    try {
      const resolved = await resolveJsonLd(primary.collection, primary.slug)
      graph = resolved ? JSON.stringify(resolved, null, 2) : ''
    } catch {
      graph = ''
    }
  }

  return (
    <aside className="how-made container" aria-label="How this page is made">
      <details className="how-made__details">
        <summary className="how-made__summary">
          <span className="how-made__icon" aria-hidden="true">
            <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.75" strokeLinecap="round" strokeLinejoin="round">
              <circle cx="6" cy="6" r="2.5" />
              <circle cx="18" cy="6" r="2.5" />
              <circle cx="12" cy="18" r="2.5" />
              <path d="M8 7.5 10.8 16M16 7.5 13.2 16M8.5 6h7" />
            </svg>
          </span>
          How this page is made
        </summary>
        <div className="how-made__body">
          <p className="how-made__intro">
            This page is rendered by a page template in the site&apos;s code from krantho documents an editor manages in{' '}
            <code>/studio</code>. The structured data below is generated by krantho from those documents.
          </p>
          <dl className="how-made__meta">
            <dt>Page template</dt>
            <dd>
              <code>krantho-site/{template}</code>
            </dd>
          </dl>
          {sources.map((source) => (
            <section key={`${source.collection}/${source.slug}`} className="how-made__source">
              <h3 className="how-made__source-title">
                <span className="badge badge--accent">{source.collection}</span>
                <code>{source.slug}</code>
              </h3>
              {source.doc && (
                <dl className="how-made__fields">
                  {fieldsOf(source.doc).map(([name, value]) => (
                    <div key={name} className="how-made__field">
                      <dt>{name}</dt>
                      <dd>{value}</dd>
                    </div>
                  ))}
                </dl>
              )}
            </section>
          ))}
          {graph && (
            <div className="how-made__jsonld">
              <h3 className="how-made__source-title">JSON-LD</h3>
              <pre>
                <code>{graph}</code>
              </pre>
            </div>
          )}
        </div>
      </details>
    </aside>
  )
}
